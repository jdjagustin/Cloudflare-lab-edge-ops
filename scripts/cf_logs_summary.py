#!/usr/bin/env python3
"""cf_logs_summary.py - read a Cloudflare Observability logs export offline and explain it.

Local only: Python standard library, no network. It never modifies the file it
reads (--redact writes a NEW file).

Input: the JSON or CSV exported from Cloudflare dashboard > Observability > Logs.
Expected fields: datetime, clientRequestHTTPMethodName, clientRequestHTTPHost,
clientRequestPath, edgeResponseStatus, cacheStatus, clientIP, clientCountryName,
originResponseStatus.
Optional fields (added in the Observability panel with the Fields button before exporting):
rayName (the cf-ray header WITHOUT the data-center suffix, for example a5837cdb9b578b33 for
cf-ray a5837cdb9b578b33-DFW) and securityAction. If present they are used; if absent nothing breaks.

Usage:
    python3 cf_logs_summary.py [file.json|file.csv]              summary + flags + sensitive-data check
    python3 cf_logs_summary.py [file] --timeline                 requests per minute (CST) by outcome
    python3 cf_logs_summary.py [file] --host lab.example.dev     only one hostname
    python3 cf_logs_summary.py [file] --rays                     one line per request with its Ray ID (needs rayName)
    python3 cf_logs_summary.py [file] --redact OUT.json|OUT.csv  write a masked copy (same format as the input)

Without a file it picks the first *observability-logs*masked* file next to this script.
Do not confuse it with har_summary.py: a HAR is the browser's view of one page load;
these logs are Cloudflare's view of every request at the edge (no headers, no timings).
"""
import argparse
import collections
import csv
import glob
import json
import os
import re
import sys
from datetime import datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
CST = timezone(timedelta(hours=-6))  # Mexico City (no daylight saving time since 2022)
FIELDS = ["datetime", "clientRequestHTTPMethodName", "clientRequestHTTPHost", "clientRequestPath",
          "edgeResponseStatus", "cacheStatus", "clientIP", "clientCountryName", "originResponseStatus"]
OPTIONAL = ["rayName", "securityAction"]
IPV4 = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")
EMAIL = re.compile(r"[A-Za-z0-9._+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
AVATAR = re.compile(r"(/avatar/)[0-9a-f]{32}")


def pick_file(arg):
    if arg:
        return arg
    for pattern in ("*observability-logs*masked*.csv", "*observability-logs*masked*.json", "*observability-logs*"):
        found = sorted(glob.glob(os.path.join(HERE, pattern)))
        if found:
            return found[0]
    sys.exit("No logs export found next to this script. Pass one as an argument.")


def load(path):
    raw = open(path, encoding="utf-8").read()
    if path.lower().endswith(".json"):
        rows = json.loads(raw)
        if not isinstance(rows, list):
            sys.exit("This JSON is not a list of log rows. Is it a HAR? Use har_summary.py for HAR files.")
    else:
        rows = list(csv.DictReader(raw.splitlines()))
    for r in rows:
        for k in ("edgeResponseStatus", "originResponseStatus"):
            r[k] = int(r.get(k) or 0)
    missing = [f for f in FIELDS if rows and f not in rows[0]]
    if missing:
        sys.exit("Missing expected fields: %s" % ", ".join(missing))
    return raw, rows


def t_utc(r):
    return datetime.fromisoformat(r["datetime"].replace("Z", "+00:00"))


def outcome(r):
    """Chart category observed to match the dashboard 'Request outcomes' chart:
    cacheStatus 'dynamic' (sent to the origin, even if that failed) counts as 'Served by Origin';
    everything else (hit, stale, revalidated, none) counts as 'Served by Cloudflare'.
    Observed on one export, not a documented rule."""
    return "origin" if r["cacheStatus"] == "dynamic" else "cloudflare"


def explain(edge, origin, cache):
    if edge == 502 and origin == 502:
        return "origin side answered 502 (tunnel up, origin down)"
    if edge == 530 and origin == 0:
        return "no origin response at all (tunnel not connected: error 1033)"
    if edge >= 500:
        return "server-side error, check origin status"
    if edge == 101:
        return "WebSocket upgrade passed through to the origin"
    if edge == 204 and origin == 0:
        return "answered by Cloudflare (for example the analytics beacon)"
    if edge == 200 and origin == 304:
        return "cache copy revalidated with the origin (conditional request)"
    if edge == 200 and origin == 0 and cache == "hit":
        return "served from edge cache, origin not contacted"
    if edge == 200 and origin == 0 and cache == "stale":
        return "expired copy served without asking the origin"
    if edge in (301, 302, 303, 307, 308) and origin == 0:
        return "redirect generated by Cloudflare itself (for example Access)"
    if edge >= 400 and origin == 0:
        return "error answered without contacting the origin"
    if edge == 200 and origin == 200:
        return "origin answered normally"
    return ""


def summary(path, rows):
    ts = [t_utc(r) for r in rows]
    print("File      :", os.path.basename(path))
    print("Requests  :", len(rows))
    if rows:
        a, b = min(ts), max(ts)
        print("First     : %s UTC = %s CST" % (a.strftime("%H:%M:%S"), a.astimezone(CST).strftime("%H:%M:%S")))
        print("Last      : %s UTC = %s CST" % (b.strftime("%H:%M:%S"), b.astimezone(CST).strftime("%H:%M:%S")))
    print("\nBy hostname:")
    for k, v in collections.Counter(r["clientRequestHTTPHost"] for r in rows).most_common():
        print("  %-34s %4d" % (k, v))
    print("\nBy cacheStatus:")
    for k, v in collections.Counter(r["cacheStatus"] for r in rows).most_common():
        print("  %-12s %4d" % (k, v))
    oc = collections.Counter(outcome(r) for r in rows)
    if rows and "securityAction" in rows[0]:
        print("\nBy securityAction (value 'unknown' appeared on requests with no security rule involved; meaning not confirmed):")
        for k, v in collections.Counter(r["securityAction"] for r in rows).most_common():
            print("  %-12s %4d" % (k, v))
    print("\nChart category (observed rule: dynamic = Served by Origin, the rest = Served by Cloudflare):")
    print("  Served by Cloudflare: %d | Served by Origin: %d" % (oc["cloudflare"], oc["origin"]))
    failed = [r for r in rows if outcome(r) == "origin" and r["edgeResponseStatus"] >= 500]
    if failed:
        print("  Note: %d of the 'Served by Origin' requests were 5xx failures." % len(failed))
    print("\nEdge status / origin status pairs:")
    pairs = collections.Counter((r["edgeResponseStatus"], r["originResponseStatus"], r["cacheStatus"]) for r in rows)
    for (e, o, c), n in sorted(pairs.items(), key=lambda kv: -kv[1]):
        print("  edge %-3d origin %-3d cache %-11s %4d  %s" % (e, o, c, n, explain(e, o, c)))
    print("\nFlags:")
    flags = []
    for r in sorted(rows, key=t_utc):
        e, o, c = r["edgeResponseStatus"], r["originResponseStatus"], r["cacheStatus"]
        if e >= 400 or c == "stale" or (300 <= e < 400):
            when = t_utc(r).astimezone(CST).strftime("%H:%M:%S")
            flags.append("%s CST %s %s%s -> %d (origin %d, cache %s)" % (
                when, r["clientRequestHTTPMethodName"], r["clientRequestHTTPHost"], r["clientRequestPath"], e, o, c))
    for line in flags or ["none"]:
        print("  -", line)


def rays(rows):
    if not rows or "rayName" not in rows[0]:
        print("\nThis export has no rayName column. In the panel use Fields > Ray ID (+), then export again.")
        return
    print("\nOne line per request (CST). Match a Ray ID with the cf-ray header from curl (ignore the -DFW suffix):")
    for r in sorted(rows, key=t_utc):
        when = t_utc(r).astimezone(CST).strftime("%H:%M:%S")
        print("  %s  %-18s %-8s edge %-3d origin %-3d %s%s" % (
            when, r["rayName"], r["cacheStatus"], r["edgeResponseStatus"], r["originResponseStatus"],
            r["clientRequestHTTPMethodName"] + " " + r["clientRequestPath"],
            ("  action=" + r["securityAction"]) if r.get("securityAction") not in (None, "", "unknown") else ""))


def timeline(rows):
    per = collections.defaultdict(lambda: [0, 0])
    for r in rows:
        per[t_utc(r).astimezone(CST).strftime("%H:%M")][0 if outcome(r) == "cloudflare" else 1] += 1
    print("\nPer minute (CST), only minutes with traffic: Served by Cloudflare / Served by Origin")
    for m in sorted(per):
        print("  %s   %3d / %3d   %s" % (m, per[m][0], per[m][1], "#" * min(per[m][0] + per[m][1], 60)))


def hygiene(raw, rows):
    ips = collections.Counter(r["clientIP"] for r in rows)
    real = [i for i in ips if IPV4.fullmatch(i)]
    print("\nSensitive-data check:")
    print("  distinct client IPs (real addresses)     :", len(real), sorted(real))
    print("  /avatar/<32-hex hash> paths               :", len(AVATAR.findall(raw)))
    print("  e-mail-like strings                       :", len(EMAIL.findall(raw)))
    if real or AVATAR.search(raw) or EMAIL.search(raw):
        print("  -> Contains personal data (client IP, avatar hash or e-mail). Use --redact before saving or sharing.")
    else:
        print("  -> No client IP, avatar hash or e-mail found. Still give it a quick look before sharing.")


def redact(path, raw, out):
    if os.path.exists(out):
        sys.exit("Refusing to overwrite: " + out)
    n_ip = n_av = n_mail = 0
    def sub(text):
        nonlocal n_ip, n_av, n_mail
        text, a = AVATAR.subn(r"\1<hash masked>", text)
        text, b = EMAIL.subn("<email masked>", text)
        text, c = IPV4.subn("x.x.x.x", text)
        n_av += a; n_mail += b; n_ip += c
        return text
    masked = sub(raw)
    if out.lower().endswith(".json"):
        json.loads(masked)  # must still be valid JSON
    with open(out, "w", encoding="utf-8") as f:
        f.write(masked)
    print("Masked copy written:", out)
    print("  IPv4 addresses masked:", n_ip, "| avatar hashes masked:", n_av, "| e-mails masked:", n_mail)
    print("Automatic masking is best effort: open the result and look for personal data before sharing it.")


def main():
    ap = argparse.ArgumentParser(description="Read a Cloudflare Observability logs export offline (see the top of the script).")
    ap.add_argument("file", nargs="?", help="logs export (.json or .csv)")
    ap.add_argument("--rays", action="store_true", help="one line per request with its Ray ID (needs the rayName column)")
    ap.add_argument("--timeline", action="store_true", help="requests per minute in CST")
    ap.add_argument("--host", help="only rows for this hostname")
    ap.add_argument("--redact", metavar="OUT", help="write a masked copy (.json or .csv)")
    args = ap.parse_args()
    path = pick_file(args.file)
    raw, rows = load(path)
    if args.redact:
        redact(path, raw, args.redact)
        return
    if args.host:
        rows = [r for r in rows if r["clientRequestHTTPHost"] == args.host]
    summary(path, rows)
    if args.timeline:
        timeline(rows)
    if args.rays:
        rays(rows)
    hygiene(raw, rows)


if __name__ == "__main__":
    main()
